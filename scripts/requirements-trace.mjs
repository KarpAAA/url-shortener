// Requirement → test traceability. Reads the ids from docs/requirements.md and the `R-xx`
// ids from test names, then writes docs/traceability.md (or, with --check, fails when it is
// stale). Always fails when a requirement has no test or a test names an unknown requirement.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import process from 'node:process';

const ROOT = join(import.meta.dirname, '..');
const REQUIREMENTS = join(ROOT, 'docs/requirements.md');
const OUTPUT = join(ROOT, 'docs/traceability.md');

/** Requirements verified by a tool other than the test runner. */
const EXTERNAL = { fuzz: 'Schemathesis (`pnpm test:contract`, CI job `contract`)' };

const LEVELS = [
  [/\.prop\.spec\.ts$/, 'property'],
  [/\.int-spec\.ts$/, 'integration'],
  [/\.e2e-spec\.ts$/, 'API'],
  [/^test\/architecture\//, 'architecture'],
  [/\.spec\.ts$/, 'unit'],
];

const walk = (dir) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === 'generated' || entry.name === 'node_modules') return [];
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });

const requirements = new Map();
for (const line of readFileSync(REQUIREMENTS, 'utf8').split(/\r?\n/)) {
  const match = /^\| (R-\d{2}) \| (.+) \| ([a-zA-Z, ]+) \|$/.exec(line);
  if (match) {
    requirements.set(match[1], {
      text: match[2].trim(),
      levels: match[3].split(',').map((level) => level.trim()),
      tests: new Map(),
    });
  }
}

const TITLE = /(['"`])((?:R-\d{2} )+.*?)\1/g;
const unknown = [];
const files = [...walk(join(ROOT, 'src')), ...walk(join(ROOT, 'test'))]
  .filter((path) => /(\.spec|-spec)\.ts$/.test(path))
  .sort();

for (const path of files) {
  const file = relative(ROOT, path).split(sep).join('/');
  const level = LEVELS.find(([pattern]) => pattern.test(file))?.[1] ?? 'unit';
  for (const [, , title] of readFileSync(path, 'utf8').matchAll(TITLE)) {
    for (const id of title.match(/R-\d{2}/g) ?? []) {
      const requirement = requirements.get(id);
      if (!requirement) {
        unknown.push(`${file}: "${title}" names ${id}, which is not in requirements.md`);
        continue;
      }
      const key = `${file}|${level}`;
      requirement.tests.set(key, (requirement.tests.get(key) ?? 0) + 1);
    }
  }
}

const problems = [...unknown];
const lines = [
  '# Traceability: requirement → tests',
  '',
  'Generated by `pnpm trace:update` from the `R-xx` ids in test names. Do not edit.',
  'A parameterised test (`it.each`) counts once, however many cases it runs.',
  '',
];

for (const [id, { text, levels, tests }] of requirements) {
  const covered = new Set([...tests.keys()].map((key) => key.split('|')[1]));
  for (const level of levels) {
    if (!(level in EXTERNAL) && !covered.has(level)) {
      problems.push(`${id} declares the "${level}" level but no ${level} test names it`);
    }
  }
  for (const level of covered) {
    if (!levels.includes(level)) {
      problems.push(`${id} has a ${level} test but requirements.md does not list that level`);
    }
  }
  lines.push(`## ${id}`, '', text, '');
  for (const [key, count] of [...tests].sort()) {
    const [file, level] = key.split('|');
    lines.push(`- ${level}: \`${file}\` (${count})`);
  }
  for (const level of levels.filter((name) => name in EXTERNAL)) {
    lines.push(`- ${level}: ${EXTERNAL[level]}`);
  }
  lines.push('');
}

if (problems.length > 0) {
  console.error(`Traceability problems:\n${problems.map((p) => `  - ${p}`).join('\n')}`);
  process.exit(1);
}

const generated = `${lines.join('\n').trimEnd()}\n`;
if (!process.argv.includes('--check')) {
  writeFileSync(OUTPUT, generated);
  console.log(`wrote docs/traceability.md: ${requirements.size} requirements, all covered`);
} else if (readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') !== generated) {
  console.error('docs/traceability.md is out of date: run "pnpm trace:update" and commit it');
  process.exit(1);
} else {
  console.log(`docs/traceability.md is up to date: ${requirements.size} requirements, all covered`);
}
